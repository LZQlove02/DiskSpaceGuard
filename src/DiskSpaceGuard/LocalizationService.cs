using System.ComponentModel;

namespace DiskSpaceGuard.Services;

public enum UiLanguage
{
    ZhCn,
    EnUs
}

/// <summary>运行时语言切换：XAML 绑定到 Loc 的索引器，切换时刷新 Item[]。</summary>
public sealed class Loc : INotifyPropertyChanged
{
    public static Loc Instance { get; } = new();

    private UiLanguage _language = UiLanguage.ZhCn;

    public UiLanguage Language => _language;

    public string this[string key] => LocalizationService.Text(key, _language);

    public void SetLanguage(UiLanguage language)
    {
        if (_language == language) return;
        _language = language;
        PropertyChanged?.Invoke(this, new PropertyChangedEventArgs("Item[]"));
    }

    public event PropertyChangedEventHandler? PropertyChanged;
}

